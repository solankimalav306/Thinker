import { recordTokenUsage, updateTokenTracker } from "./token-usage.js";
import { escapeHtml, renderMarkdown } from "./safe-html.js";

const DEFAULT_CHAT_MODEL = "gemini-3.5-flash-lite";

function processCitations(html) {
  let processed = html.replace(/\[?Page\s+(\d+)\]?[.:]?/gi, '<button class="citation-tag page-citation" data-page="$1" title="Go to Page $1"><i class="fa-solid fa-file-pdf"></i> Page $1</button>');
  processed = processed.replace(/\[?(AI\s+Knowledge|External\s+Knowledge|AI\s+Insight)\]?[.:]?/gi, '<span class="citation-tag ai-citation" title="Generated by AI Brain"><i class="fa-solid fa-sparkles"></i> AI Knowledge</span>');
  return processed;
}

function markdownToHtml(text) {
  return processCitations(renderMarkdown(text));
}

function summarizeText(text, max = 120) {
  const clean = String(text || "").replace(/\s+/g, " ").trim();
  if (clean.length <= max) return clean;
  return `${clean.slice(0, max - 1)}...`;
}

export class ChatController {
  constructor(options) {
    this.chatHistory = options.chatHistory;
    this.chatInput = options.chatInput;
    this.chatSend = options.chatSend;
    this.selectedTextBox = options.selectedTextBox;
    this.selectedTextBox.addEventListener("click", () => {
      if (this.selectedTextBox.classList.contains("collapsible")) {
        this.selectedTextBox.classList.toggle("collapsed");
      }
    });
    this.imagePreviewContainer = options.imagePreviewContainer;
    this.onStatus = options.onStatus;
    this.onSaveNote = options.onSaveNote;
    this.getChatConfig = options.getChatConfig;
    this.onAgentAction = options.onAgentAction;
    this.onGlossaryTermFound = options.onGlossaryTermFound;
    this.onTokenUsage = options.onTokenUsage;
    this.tokenTracker = options.tokenTracker;
    this.summarizeCacheBtn = options.summarizeCacheBtn;

    this.attachedImage = null;
    this.activePdfPath = null;
    this.enabled = true;
    this.entries = [];
  }

  setEnabled(enabled) {
    this.enabled = enabled;
    this.chatInput.disabled = !enabled;
    this.chatSend.disabled = !enabled;
    if (!enabled) {
      this.chatInput.blur();
    }
  }

  resetUi() {
    this.chatHistory.innerHTML = "";
    this.clearSelectedText();
    this.clearAttachment();
  }

  appendMessage(sender, text, image = null, usage = null) {
    const msg = document.createElement("div");
    msg.className = sender === "You" ? "user-msg" : "bot-msg";

    let html = "";
    if (image) {
      html += `<img src="${image}" style="max-width:100%; border-radius:8px; margin-bottom:8px;" alt="Attachment">`;
    }

    if (sender === "Bot") {
      if (/\[AI_INSIGHT\]/i.test(text)) {
        text = text.replace(/\[AI_INSIGHT\]/gi, "").trim();
        html += `<div class="ai-insights-header"><i class="fa-solid fa-brain"></i> AI Insights</div>`;
      } else if (/\[DOC_ONLY\]/i.test(text)) {
        text = text.replace(/\[DOC_ONLY\]/gi, "").trim();
        html += `<div class="ai-insights-header doc-only-header"><i class="fa-solid fa-file-pdf"></i> Document Only</div>`;
      }
    }

    html += markdownToHtml(text);
    
    // Subtle Evaluation Footnote
    if (usage && usage.evaluation) {
      const evalData = usage.evaluation;
      const score = Number(evalData.score);
      if (Number.isFinite(score)) {
        const precisionLabel = score > 0.8 ? "High Precision" : score > 0.5 ? "Standard Precision" : "Low Precision";
        html += `<div class="message-subtle-eval"><i class="fa-solid fa-circle-info"></i> ${precisionLabel} response</div>`;
      }
    }

    // Subtle Action Pills
    if (usage && usage.actions && usage.actions.length > 0) {
      const pages = [...new Set(usage.actions.map(a => Number(a.page)).filter(p => Number.isFinite(p)))];
      if (pages.length > 0) {
        html += `<div class="message-action-pills">`;
        pages.forEach(p => {
          html += `<button class="agent-action-pill" data-nav-page="${p}"><i class="fa-solid fa-location-dot"></i> Page ${p}</button>`;
        });
        html += `</div>`;
      }
    }

    if (usage && usage.totalTokenCount) {
      const prompt = usage.promptTokens || 0;
      const response = usage.responseTokens || 0;
      const detail = prompt || response ? ` (${prompt} in, ${response} out)` : "";
      html += `<div style="text-align: right; font-size: 0.65rem; color: var(--text-soft); margin-top: 6px; font-family: monospace; border-top: 1px dashed var(--line); padding-top: 4px; opacity: 0.5;">Tokens: ${usage.totalTokenCount}${detail}</div>`;
    }

    msg.innerHTML = html;
    if (sender === "Bot") msg.appendChild(this.buildMessageActions(text));
    this.chatHistory.appendChild(msg);
    this.chatHistory.scrollTop = this.chatHistory.scrollHeight;
  }

  buildMessageActions(text) {
    const row = document.createElement("div");
    row.className = "message-actions";

    const copy = document.createElement("button");
    copy.type = "button";
    copy.className = "message-action-btn";
    copy.innerHTML = '<i class="fa-regular fa-copy"></i> Copy';
    copy.addEventListener("click", async () => {
      try {
        await navigator.clipboard.writeText(text);
        this.onStatus("Answer copied.");
      } catch {
        this.onStatus("Could not copy to the clipboard.");
      }
    });
    row.appendChild(copy);

    if (this.onSaveNote) {
      const save = document.createElement("button");
      save.type = "button";
      save.className = "message-action-btn";
      save.innerHTML = '<i class="fa-solid fa-note-sticky"></i> Save as note';
      save.addEventListener("click", () => {
        this.onSaveNote(text);
        save.disabled = true;
        save.innerHTML = '<i class="fa-solid fa-check"></i> Saved';
      });
      row.appendChild(save);
    }
    return row;
  }

  appendWelcomeMessage() {
    const welcome = document.createElement("div");
    welcome.className = "agent-welcome";
    welcome.innerHTML = `
      <h3><i class="fa-solid fa-wand-magic-sparkles"></i> Thinker Agent</h3>
      <p>I'm your AI research assistant. I can help you analyze this document, define complex terms, and generate study materials.</p>
      <div class="capabilities-grid">
        <div class="capability-chip" data-query="Summarize the main points of this document">
          <i class="fa-solid fa-file-invoice"></i>
          <span>Summarize PDF</span>
        </div>
        <div class="capability-chip" data-query="Identify and define the key technical terms">
          <i class="fa-solid fa-spell-check"></i>
          <span>Define Terms</span>
        </div>
        <div class="capability-chip" data-query="Generate structured notes from the current page">
          <i class="fa-solid fa-note-sticky"></i>
          <span>Create Notes</span>
        </div>
        <div class="capability-chip" data-query="Identify the core concepts and their relationships">
          <i class="fa-solid fa-diagram-project"></i>
          <span>Map Concepts</span>
        </div>
      </div>
    `;
    
    welcome.querySelectorAll(".capability-chip").forEach(chip => {
      chip.addEventListener("click", () => {
        this.chatInput.value = chip.dataset.query;
        this.sendMessage();
      });
    });

    this.chatHistory.appendChild(welcome);
  }

  appendCacheSummary(summaryText, auto = false) {
    if (!summaryText) return;

    const msg = document.createElement("div");
    msg.className = "bot-msg cache-summary-msg";
    msg.innerHTML = `
      <div class="cache-summary-header">
        <i class="fa-solid fa-brain"></i>
        ${auto ? "Knowledge Cache Auto-Summary" : "Knowledge Cache Summary"}
      </div>
      ${markdownToHtml(summaryText)}
    `;
    this.chatHistory.appendChild(msg);
    this.chatHistory.scrollTop = this.chatHistory.scrollHeight;
  }



  appendUserMessage(question, quoteText, image = null) {
    const msg = document.createElement("div");
    msg.className = "user-msg";

    let html = "";
    if (image) {
      html += `<img src="${image}" style="max-width:100%; border-radius:8px; margin-bottom:8px;" alt="Attachment">`;
    }

    if (quoteText) {
      html += `<blockquote class="chat-quote">${escapeHtml(quoteText)}</blockquote>`;
    }

    html += `<div class="chat-question">${escapeHtml(question)}</div>`;
    msg.innerHTML = html;

    this.chatHistory.appendChild(msg);
    this.chatHistory.scrollTop = this.chatHistory.scrollHeight;
  }



  setSelectedText(text) {
    if (!text) {
      this.selectedTextBox.textContent = "";
      this.selectedTextBox.style.display = "none";
      return;
    }

    this.selectedTextBox.textContent = text;
    this.selectedTextBox.style.display = "";
    // Long selections show a few lines; clicking the box expands it. The full text stays in
    // textContent, which is what gets sent with the question.
    const long = text.length > 160 || text.split("\n").length > 3;
    this.selectedTextBox.classList.toggle("collapsible", long);
    this.selectedTextBox.classList.toggle("collapsed", long);
    this.selectedTextBox.title = long ? "Click to expand or collapse" : "";
  }

  clearSelectedText() {
    this.setSelectedText("");
  }

  attachImage(dataUrl) {
    this.attachedImage = dataUrl;
    this.imagePreviewContainer.innerHTML = `
      <img src="${dataUrl}" alt="Screenshot preview" />
      <button id="remove-image-btn" title="Remove image">x</button>
    `;
    this.imagePreviewContainer.style.display = "block";
    const removeBtn = document.getElementById("remove-image-btn");
    removeBtn.addEventListener("click", () => this.clearAttachment());
  }

  clearAttachment() {
    this.attachedImage = null;
    this.imagePreviewContainer.innerHTML = "";
    this.imagePreviewContainer.style.display = "none";
  }

  async loadPdfHistory(pdfPath) {
    this.activePdfPath = pdfPath;
    this.entries = [];
    this.resetUi();

    if (!window.electronAPI || !window.electronAPI.loadChatHistory || !pdfPath) {
      return;
    }

    const loaded = await window.electronAPI.loadChatHistory(pdfPath);
    this.entries = Array.isArray(loaded) ? loaded : [];
    
    if (this.entries.length === 0) {
      this.appendWelcomeMessage();
    }

    this.entries.forEach((entry) => {
      if (entry.role === "user") {
        this.appendUserMessage(entry.question || entry.text || "", entry.quote || "", null);
      } else {
        this.appendMessage("Bot", entry.text || "");
      }
    });
  }

  async persistEntry(entry) {
    if (!window.electronAPI || !window.electronAPI.appendChatEntry || !this.activePdfPath) {
      return;
    }

    await window.electronAPI.appendChatEntry({
      pdfPath: this.activePdfPath,
      entry
    });
  }

  summarizeContext() {
    if (this.entries.length === 0) {
      return "";
    }

    // Keep only the last 6 turns, truncate each to 120 chars to save tokens
    const recent = this.entries.slice(-6).map((entry) => {
      const prefix = entry.role === "user" ? "U" : "A";
      const text = (entry.text || "").replace(/\s+/g, " ").trim();
      return `${prefix}: ${text.slice(0, 120)}`;
    });

    const summary = recent.join("\n");
    return summary.length > 600 ? summary.slice(summary.length - 600) : summary;
  }

  getChatConfigOrPrompt() {
    const config = this.getChatConfig ? this.getChatConfig() : null;

    if (config?.profile) {
      return config;
    }

    if (config?.apiKey) {
      return config;
    }

    const entered = window.prompt("Enter API key (optional for local or profile-based providers):");
    if (entered && entered.trim()) {
      return {
        apiKey: entered.trim(),
        profile: { format: "gemini", model: config?.model || DEFAULT_CHAT_MODEL, key: entered.trim() },
        model: config?.model || DEFAULT_CHAT_MODEL,
        apiKeyLabel: "Manual key"
      };
    }

    return {
      apiKey: "",
      profile: null,
      model: config?.model || DEFAULT_CHAT_MODEL,
      apiKeyLabel: "No profile selected"
    };
  }

  

  async askLLM(parts) {
    const { apiKey, profile, model } = this.getChatConfigOrPrompt();

    if (!profile && !apiKey) {
      throw new Error("Missing AI profile or API key");
    }

    if (window.electronAPI && window.electronAPI.askLLM) {
      const result = await window.electronAPI.askLLM({
        profile: profile || { format: "gemini", key: apiKey, model: model || DEFAULT_CHAT_MODEL },
        model: model || DEFAULT_CHAT_MODEL,
        apiKey,
        parts
      });

      if (!result?.ok) {
        throw new Error(result?.error || "AI request failed");
      }

      return result.text || "No response.";
    }

    throw new Error("AI bridge not available");
  }

  async askGemini(parts) {
    return this.askLLM(parts);
  }

  async sendMessage() {
    if (!this.enabled) {
      this.onStatus("Open a PDF first. Chat is disabled on welcome screen.");
      return;
    }

    const text = this.chatInput.value.trim();
    if (!text && !this.attachedImage) {
      return;
    }

    if (!this.activePdfPath) {
      this.onStatus("Open a PDF tab to chat about it.");
      return;
    }

    const contextText = this.selectedTextBox.textContent.trim();
    const questionText = text;
    const summary = this.summarizeContext();

    this.appendUserMessage(questionText, contextText, this.attachedImage);
    const userEntry = {
      role: "user",
      text: contextText ? `Quote: "${contextText}"\nQuestion: ${questionText}` : questionText,
      question: questionText,
      quote: contextText,
      ts: Date.now()
    };
    this.entries.push(userEntry);
    await this.persistEntry(userEntry);

    const parts = [];
    if (this.attachedImage) {
      parts.push({
        inline_data: {
          mime_type: "image/png",
          data: this.attachedImage.split(",")[1]
        }
      });
    }
    const pdfId = await window.electronAPI.getPdfId(this.activePdfPath);
    const storagePath = await window.electronAPI.getUserDataPath();
    const config = this.getChatConfigOrPrompt();

    this.chatInput.value = "";
    this.clearAttachment();
    this.clearSelectedText();
    this.onStatus("Agent is thinking...");

    const typingId = "typing-indicator-" + Date.now();
    const typingHtml = `
      <div class="bot-msg thinking-container" id="${typingId}">
        <div class="typing-dots"><span></span><span></span><span></span></div>
        <div class="thinking-steps" id="${typingId}-steps">
          <div class="thinking-step active" id="${typingId}-step-1"><i class="fa-solid fa-circle-notch fa-spin"></i> Analyzing your request...</div>
        </div>
      </div>
    `;
    this.chatHistory.insertAdjacentHTML("beforeend", typingHtml);
    this.chatHistory.scrollTop = this.chatHistory.scrollHeight;

    const updateStep = (id, text, done = false) => {
      const stepEl = document.getElementById(id);
      if (stepEl) {
        stepEl.innerHTML = `<i class="fa-solid ${done ? 'fa-check' : 'fa-circle-notch fa-spin'}"></i> ${text}`;
        stepEl.className = `thinking-step ${done ? 'done' : 'active'}`;
      }
    };

    const addStep = (containerId, stepId, text) => {
      const container = document.getElementById(containerId);
      if (container) {
        const step = document.createElement("div");
        step.id = stepId;
        step.className = "thinking-step active";
        step.innerHTML = `<i class="fa-solid fa-circle-notch fa-spin"></i> ${text}`;
        container.appendChild(step);
      }
    };

    try {
      // Simulate step-by-step progress for better UX
      setTimeout(() => updateStep(`${typingId}-step-1`, "Intent classified", true), 800);
      setTimeout(() => addStep(`${typingId}-steps`, `${typingId}-step-2`, "Retrieving document context..."), 900);
      setTimeout(() => updateStep(`${typingId}-step-2`, "Context retrieved (3 relevant pages)", true), 1800);
      setTimeout(() => addStep(`${typingId}-steps`, `${typingId}-step-3`, "Generating response..."), 1900);

      const res = await window.electronAPI.invokeAgent({
        query: questionText,
        pdfId,
        storagePath,
        apiKey: config.apiKey,
        apiFormat: config.profile?.format || 'gemini',
        apiUrl: config.profile?.url || '',
        model: config.model,
        profile: config.profile || null,
        context: contextText,
        messages: this.entries.slice(-10),
        parts: parts
      });

      document.getElementById(typingId)?.remove();

      if (!res.ok) {
        throw new Error(res.error || "Agent request failed");
      }

      const agentRes = res.result;
      console.debug('Agent result actions:', agentRes.actions);
      console.debug('Agent raw response_text:', agentRes.response_text);

      // Prefer concise user-facing messages when the agent produced notes,
      // avoid surfacing internal critic/meta-analysis strings directly.
      let replyText = agentRes.response_text || "No response.";
      const hasNoteAction = agentRes.actions && agentRes.actions.some(a => a.type === 'note');
      if (hasNoteAction) {
        const noteAction = agentRes.actions.find(a => a.type === 'note');
        const excerpt = (noteAction?.content || '').slice(0, 200).trim();
        replyText = `Generated structured notes saved to Research Notes panel.${excerpt ? "\n\n" + excerpt : ""}`;
      }

      // Selective Interactivity: Only show interactive pills for explanations, questions, or analytical responses
      const isInteractiveIntent = (agentRes.intent === 'explain' || agentRes.intent === 'question' || agentRes.intent === 'analyze') 
        || /explain|why|how|what|detail|analyze|question|\?/.test(questionText.toLowerCase());

      const botMetadata = {
        totalTokenCount: agentRes.usage?.total_tokens || 0,
        promptTokens: agentRes.usage?.prompt_tokens || 0,
        responseTokens: agentRes.usage?.response_tokens || 0,
        actions: isInteractiveIntent ? (agentRes.actions || []) : [],
        evaluation: agentRes.evaluation || null
      };

      if (agentRes.cache_summary) {
        this.appendCacheSummary(agentRes.cache_summary, true);
      }

      this.appendMessage("Bot", replyText, null, botMetadata);

      if (agentRes.usage) {
        updateTokenTracker(this.tokenTracker, agentRes.usage);
        await recordTokenUsage({
          profileId: config.profile?.id || agentRes.usage.profile_id,
          profileLabel: config.profile?.label || config.apiKeyLabel || "Unknown",
          usage: agentRes.usage,
          pdfId,
        });
        if (this.onTokenUsage) this.onTokenUsage();
      }

      const botEntry = {
        role: "assistant",
        text: replyText,
        ts: Date.now()
      };
      this.entries.push(botEntry);
      await this.persistEntry(botEntry);

      // Handle actions if any
      if (agentRes.actions && agentRes.actions.length > 0) {
        if (this.onAgentAction) {
          agentRes.actions.forEach(action => this.onAgentAction(action));
        }
      }

      // Handle glossary terms if any
      if (agentRes.glossary_terms && agentRes.glossary_terms.length > 0) {
        if (this.onGlossaryTermFound) {
          agentRes.glossary_terms.forEach(term => this.onGlossaryTermFound(term));
        }
      }

      this.onStatus("Ready.");
    } catch (error) {
      console.error(error);
      document.getElementById(typingId)?.remove();
      this.appendMessage("Bot", `Agent request failed: ${error?.message || "Unknown error"}`);
      this.onStatus("Agent request failed.");
    }
  }

  async summarizeKnowledgeCache() {
    if (!this.enabled || !this.activePdfPath) {
      this.onStatus("Open a PDF first to summarize the knowledge cache.");
      return;
    }

    const config = this.getChatConfigOrPrompt();
    if (!config?.profile && !config?.apiKey) {
      this.onStatus("Select an AI profile before summarizing.");
      return;
    }

    const pdfId = await window.electronAPI.getPdfId(this.activePdfPath);
    const storagePath = await window.electronAPI.getUserDataPath();

    this.onStatus("Summarizing knowledge cache...");
    try {
      const res = await window.electronAPI.summarizeCache({
        pdfId,
        storagePath,
        apiKey: config.apiKey,
        apiFormat: config.profile?.format || "gemini",
        apiUrl: config.profile?.url || "",
        model: config.model,
        profile: config.profile || null,
        profileId: config.profile?.id,
      });

      if (!res.ok) throw new Error(res.error || "Summarization failed");

      const summaryText = res.result?.summary || "";
      if (summaryText) {
        this.appendCacheSummary(summaryText, false);
        this.onStatus("Knowledge cache summarized.");
      } else {
        this.onStatus(res.result?.message || "Nothing to summarize.");
      }

      if (res.result?.usage) {
        updateTokenTracker(this.tokenTracker, res.result.usage);
        await recordTokenUsage({
          profileId: config.profile?.id || res.result.usage.profile_id,
          profileLabel: config.profile?.label || "Unknown",
          usage: res.result.usage,
          pdfId,
        });
        if (this.onTokenUsage) this.onTokenUsage();
      }
    } catch (error) {
      console.error(error);
      this.onStatus(`Cache summarization failed: ${error?.message || "Unknown error"}`);
    }
  }

  bindEvents() {
    this.chatSend.addEventListener("click", () => this.sendMessage());

    if (this.summarizeCacheBtn) {
      this.summarizeCacheBtn.addEventListener("click", () => this.summarizeKnowledgeCache());
    }

    this.chatInput.addEventListener("keydown", (event) => {
      if (event.key === "Enter" && !event.shiftKey) {
        event.preventDefault();
        this.sendMessage();
      }
    });

    this.chatHistory.addEventListener("click", (event) => {
      const citation = event.target.closest(".page-citation");
      if (citation) {
        const pageNum = parseInt(citation.getAttribute("data-page"), 10);
        if (!isNaN(pageNum)) {
          window.dispatchEvent(new CustomEvent("navigate-pdf-page", { detail: { page: pageNum } }));
        }
      }

      const actionBtn = event.target.closest(".agent-action-btn, .agent-action-pill");
      if (actionBtn) {
        const pageNum = parseInt(actionBtn.getAttribute("data-nav-page"), 10);
        if (!isNaN(pageNum)) {
          window.dispatchEvent(new CustomEvent("navigate-pdf-page", { detail: { page: pageNum } }));
        }
      }
    });
  }
}
